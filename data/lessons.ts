type ExtraLesson = Pick<
  Lesson,
  "id" | "unitId" | "languageId" | "title" | "description" | "goal" | "imageUrl"
> & {
  term: string;
  translation: string;
};

const createLesson = ({ term, translation, ...lesson }: ExtraLesson): Lesson => ({
  ...lesson,
  xpReward: 10,
  vocabulary: [{ term, translation }],
  phrases: [{ text: term, translation }],
  activities: [
    {
      id: `${lesson.id}-choice`,
      type: "multiple-choice",
      prompt: `What does “${term}” mean?`,
      choices: [translation, "Goodbye", "Please"],
      correctAnswer: translation,
    },
    {
      id: `${lesson.id}-speak`,
      type: "speaking",
      prompt: "Say this phrase aloud.",
      phrase: term,
      translation,
    },
  ],
  aiTeacherPrompt: `Teach a friendly beginner ${lesson.languageId} lesson about ${lesson.title}. Model the phrase slowly, give the learner time to repeat it, and offer encouragement.`,
});

